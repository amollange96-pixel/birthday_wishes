import { PhotoItem } from '../types';

/**
 * Resolves a photo path relative to the application public directory,
 * properly respecting Vite base path and URL encoding filenames with spaces/parentheses.
 */
export const getPhotoPublicUrl = (filename: string): string => {
  const base = import.meta.env?.BASE_URL || '/';
  const cleanBase = base.endsWith('/') ? base : `${base}/`;
  return `${cleanBase}assets/photos/${encodeURIComponent(filename)}`;
};

